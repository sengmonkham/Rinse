"""Character fingerprint matching (brainrot characters & known AI artwork).

Replaces server.py's single-dHash loop with a two-of-three perceptual-hash
matcher over fingerprints/db.py (generated by scripts/build_fingerprints.py).

Why two-of-three: dHash alone false-positives on near-flat/white regions
(any large blank area has a trivial dHash). Since a confirmed match hard-
forces the SynthID layer to 99 (existing behavior), false positives are
expensive. dHash must agree AND at least one of pHash/aHash must corroborate
before we call it a match — except for legacy seeds, which have no source
file and therefore carry only a dHash (they keep the historical <=10 rule
and are marked strength "likely" rather than "exact").

Thresholds (of 64 bits):
  dhash: <= DHASH_EXACT (6) exact, <= DHASH_MAX (10) candidate
  phash: <= PHASH_MAX (12) corroboration
  ahash: <= AHASH_MAX (10) corroboration
Tune only via scripts/eval_fingerprints.py evidence (see plan doc §5).
"""

from __future__ import annotations

from typing import Any

from PIL import Image

from forensics.hashing import ahash, dhash, hamming, phash

try:
    from fingerprints.db import FINGERPRINTS  # generated
except Exception:  # noqa: BLE001 — DB not built yet
    FINGERPRINTS = []

# --- thresholds -----------------------------------------------------------
DHASH_EXACT = 6
DHASH_MAX = 10
PHASH_MAX = 12
AHASH_MAX = 10

# Legacy seeds have no canonical file, so only their dHash can be compared.
# They keep the historical single-hash rule (<= 10) and are never "exact".
LEGACY_STRENGTH = "likely"


def _match_one(
    entry: dict[str, Any], q: dict[str, int]
) -> tuple[int, str] | None:
    """Match a query hash triplet against one DB entry.

    Returns (dhash_distance, strength) when the entry matches, else None.
    """
    d_dhash = hamming(q["dhash"], entry["dhash"])
    if d_dhash > DHASH_MAX:
        return None

    # Legacy seed: dhash-only, historical rule.
    if entry.get("phash") is None:
        return (d_dhash, LEGACY_STRENGTH) if d_dhash <= DHASH_MAX else None

    # Two-of-three agreement for hashed refs.
    if d_dhash <= DHASH_EXACT:
        # Very close dHash: accept when either secondary hash agrees.
        d_phash = hamming(q["phash"], entry["phash"])
        d_ahash = hamming(q["ahash"], entry["ahash"])
        if d_phash <= PHASH_MAX or d_ahash <= AHASH_MAX:
            return (d_dhash, "exact")
        # dHash is near-identical but no corroboration: treat as weak.
        return (d_dhash, "weak")

    # 7..10: require BOTH secondary hashes to agree (stricter band).
    d_phash = hamming(q["phash"], entry["phash"])
    d_ahash = hamming(q["ahash"], entry["ahash"])
    if d_phash <= PHASH_MAX and d_ahash <= AHASH_MAX:
        return (d_dhash, "likely")
    return None


def match_character(img: Image.Image) -> dict[str, Any] | None:
    """Match an image against the character fingerprint DB.

    Returns the best match as:
        {
          "match": "<character-id>",
          "label": "<human label>",
          "ref": "<canonical file / legacy>",
          "distance": {"dhash": int, "phash": int | None, "ahash": int | None},
          "match_strength": "exact" | "likely" | "weak",
        }
    or None when nothing matches.

    Best-match selection: strength rank first (exact > likely > weak), then
    smallest dHash distance.
    """
    if not FINGERPRINTS:
        return None

    q: dict[str, int] = {
        "dhash": dhash(img),
        "phash": phash(img),
        "ahash": ahash(img),
    }

    candidates: list[tuple[int, str, dict[str, Any], dict[str, int]]] = []

    for entry in FINGERPRINTS:
        hit = _match_one(entry, q)
        if hit is None:
            continue
        d, strength = hit
        dist = {"dhash": d}
        if entry.get("phash") is not None:
            dist["phash"] = hamming(q["phash"], entry["phash"])
            dist["ahash"] = hamming(q["ahash"], entry["ahash"])
        candidates.append((d, strength, entry, dist))

    # Center-crop fallback for memes where the character sits on a busy
    # background: hash the central 60% and 36% crops too.
    w, h = img.size
    if w >= 64 and h >= 64:
        for frac in (0.6, 0.36):
            cw, ch = int(w * frac), int(h * frac)
            left, top = (w - cw) // 2, (h - ch) // 2
            crop = img.crop((left, top, left + cw, top + ch))
            cq = {
                "dhash": dhash(crop),
                "phash": phash(crop),
                "ahash": ahash(crop),
            }
            for entry in FINGERPRINTS:
                if entry.get("phash") is None:
                    continue  # crop path only applies to hashed refs
                hit = _match_one(entry, cq)
                if hit is None:
                    continue
                d, strength = hit
                # Crop matches cap at "likely" — framing changed.
                if strength == "exact":
                    strength = "likely"
                dist = {
                    "dhash": d,
                    "phash": hamming(cq["phash"], entry["phash"]),
                    "ahash": hamming(cq["ahash"], entry["ahash"]),
                }
                candidates.append((d, strength, entry, dist))

    if not candidates:
        return None

    rank = {"exact": 0, "likely": 1, "weak": 2}
    candidates.sort(key=lambda c: (rank[c[1]], c[0]))
    d, strength, entry, dist = candidates[0]

    return {
        "match": entry["character"],
        "label": entry["label"],
        "ref": entry.get("ref", ""),
        "distance": dist,
        "match_strength": strength,
    }


def match_label_for_reason(m: dict[str, Any]) -> str:
    """Human reason line for the fused verdict's reasons list."""
    d = m.get("distance", {})
    dstr = d.get("dhash")
    dist_part = f", d={dstr}" if dstr is not None else ""
    return f"{m['label']} (perceptual fingerprint match{dist_part})"
